const NOISE_PATTERNS = [
  /^home$/i,
  /^about us$/i,
  /^latest news$/i,
  /^copyright/i,
  /^designed & developed/i,
  /^falang translation/i,
  /^last update/i,
  /^search \.\.\.$/i,
];

async function main() {
  const chunks = [];
  const failures = [];
  const fetchedAt = new Date().toISOString().slice(0, 10);

  for (const source of SOURCES) {
    try {
      const html = await fetchText(source.url);
      const text = extractUsefulText(html, source);
      const pageChunks = chunkText(text, 1100, 220);

      pageChunks.forEach((content, index) => {
        chunks.push({
          id: stableId(`${source.title}-${index + 1}`),
          title: pageChunks.length > 1 ? `${source.title} (${index + 1})` : source.title,
          category: source.category,
          summary: summarize(content),
          content,
          source: {
            title: source.title,
            url: source.url,
          },
          lastVerified: fetchedAt,
          keywords: [...source.keywords, ...extractKeywords(content)],
          generated: true,
        });
      });
    } catch (error) {
      failures.push({ url: source.url, message: error instanceof Error ? error.message : String(error) });
    }
  }

  const moduleText = [
    'import type { DmtKnowledgeChunk } from "../types/domain";',
    "",
    "// Generated by `npm run crawl:dmt`. Do not hand-edit generated chunks.",
    `// Last generated: ${new Date().toISOString()}`,
    `export const GENERATED_DMT_KNOWLEDGE: DmtKnowledgeChunk[] = ${JSON.stringify(chunks, null, 2)};`,
    "",
  ].join("\n");

  await mkdir(dirname(OUT_FILE), { recursive: true });
  await writeFile(OUT_FILE, moduleText, "utf8");

  console.log(`Generated ${chunks.length} chunks at ${OUT_FILE}`);
  if (failures.length) {
    console.warn("Some pages could not be crawled:");
    for (const failure of failures) {
      console.warn(`- ${failure.url}: ${failure.message}`);
    }
  }
}

async function fetchText(url) {
  const response = await fetch(url, {
    headers: {
      "user-agent": "DMT-Assist-RAG/1.0 (+https://dmtappointments.dmt.gov.lk/)",
      accept: "text/html,application/xhtml+xml",
    },
  });

  if (!response.ok) {
    throw new Error(`HTTP ${response.status}`);
  }

  return response.text();
}

function extractUsefulText(html, source) {
  const text = html
    .replace(/<script[\s\S]*?<\/script>/gi, " ")
    .replace(/<style[\s\S]*?<\/style>/gi, " ")
    .replace(/<noscript[\s\S]*?<\/noscript>/gi, " ")
    .replace(/<\/(p|li|h1|h2|h3|h4|tr|div|section)>/gi, "\n")
    .replace(/<[^>]+>/g, " ")
    .replace(/&nbsp;/g, " ")
    .replace(/&#160;/g, " ")
    .replace(/&amp;/g, "&")
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/\u00c2\u00b7/g, "-")
    .replace(/\u00e2\u20ac\u201c|\u00e2\u20ac\u201d/g, "-")
    .replace(/\u00e2\u20ac\u2122/g, "'")
    .replace(/\u00e2\u20ac\u0153|\u00e2\u20ac\u009d/g, '"')
    .replace(/\s+\n/g, "\n")
    .replace(/\n\s+/g, "\n")
    .split("\n")
    .map((line) => line.replace(/\s+/g, " ").trim())
    .filter(
      (line) =>
        line.length > 2 &&
        !NOISE_PATTERNS.some((pattern) => pattern.test(line)) &&
        !looksLikeMojibake(line)
    )
    .join("\n");

  return cropToMainContent(text, source.title);
}

function cropToMainContent(text, title) {
  const lowerText = text.toLowerCase();
  const breadcrumbIndex = lowerText.lastIndexOf("you are here");

  if (breadcrumbIndex >= 0) {
    return trimFooter(text.slice(breadcrumbIndex).replace(/^you are here:?\s*/i, ""));
  }

  const lowerTitle = title.toLowerCase();
  const titleIndex = lowerText.lastIndexOf(lowerTitle);
  const start = titleIndex >= 0 ? titleIndex : 0;
  return trimFooter(text.slice(start));
}

function trimFooter(text) {
  const stopMarkers = ["Latest News", "Copyright", "Designed & Developed", "FaLang translation"];
  const stop = stopMarkers
    .map((marker) => text.indexOf(marker))
    .filter((index) => index > 120)
    .sort((a, b) => a - b)[0];

  return (stop ? text.slice(0, stop) : text).trim();
}

function chunkText(text, maxLength, overlap) {
  const paragraphs = text.split(/\n+/).filter(Boolean);
  const chunks = [];
  let current = "";

  for (const paragraph of paragraphs) {
    if ((current + "\n" + paragraph).length > maxLength && current.length > 200) {
      chunks.push(current.trim());
      current = current.slice(Math.max(0, current.length - overlap));
    }

    current = `${current}\n${paragraph}`.trim();
  }

  if (current.length > 120) {
    chunks.push(current.trim());
  }

  return chunks;
}

function summarize(text) {
  const firstSentence = text
    .replace(/\n/g, " ")
    .split(/(?<=[.!?])\s+/)
    .find((sentence) => sentence.length > 40);

  return (firstSentence || text.replace(/\n/g, " ")).slice(0, 280);
}

function extractKeywords(text) {
  const matches = text
    .toLowerCase()
    .match(/\b(?:mta|cmt|licen[cs]e|registration|transfer|vehicle|medical|certificate|appointment|revenue|passport|identity|nic|permit|form|tax)\b/g);

  return [...new Set(matches ?? [])].slice(0, 12);
}

function looksLikeMojibake(line) {
  const extendedLatinMatches = line.match(/[\u00c0-\u00ff]/g)?.length ?? 0;
  return extendedLatinMatches > Math.max(3, line.length * 0.08);
}

function stableId(value) {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

